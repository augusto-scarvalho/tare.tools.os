"""SPEC-112 records ledger: a three-layer project memory.

Layer model (decided; see specs/40-features/records-ledger.md, v2 amendment):
- **canonical** = git-diffable JSON on disk (`.harness/state/worklog.json` +
  `worklog-archive.json`), the single write path for historical records; class B
  (untracked here) — history/durability live in the private state home
  (tools/state_home_sync.py);
- **derived** = a SQLite/FTS5 index (`.harness/state-store/records.db`,
  gitignored) rebuilt on demand from the canonical JSON plus other state files;
- **head** = one small always-in-context section rendered into CONTEXT.md.

Grounding:
- MemGPT (arXiv:2310.08560): core (always-in-context) vs archival memory — the
  head is core, the index is archival, queried through a tool.
- PROJECTMEM (arXiv:2606.12329): an event-sourced SQLite ledger with
  regenerable projections — canonical JSON is the log, the db is a projection.
- Generative Agents (arXiv:2304.03442): retrieval by recency/relevance returns
  handles, never large bodies, to keep context small.
- Anthropic "Effective context engineering": just-in-time handles the agent
  dereferences on demand instead of pre-loading the whole corpus.
"""
