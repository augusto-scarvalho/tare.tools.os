LOG_KINDS = ("milestone", "change", "decision", "release", "note")

WORKLOG_REL = ".harness/state/worklog.json"
ARCHIVE_REL = ".harness/state/worklog-archive.json"
DB_REL = ".harness/state-store/records.db"
CONTEXT_REL = ".harness/context/CONTEXT.md"
# Class-B split: the autogenerated head lives in its own (untracked) file so
# CONTEXT.md stays pure class-A documentation; session hooks inject both.
LEDGER_HEAD_REL = ".harness/context/LEDGER_HEAD.md"
ESCALATIONS_REL = ".harness/state/escalations.json"
COST_REL = ".harness/state/cost-metrics.json"
SELF_REVIEW_REL = ".harness/state/self-review.json"
QUALITY_REL = ".harness/state/quality-state.json"

HOT_MAX = 300
HEAD_START = "<!-- ledger:head:start -->"
HEAD_END = "<!-- ledger:head:end -->"
HEAD_MAX_LINES = 30  # total lines between markers, inclusive

# Index sources whose mtime drives staleness (JSON state + git tip).
_STALE_SOURCES = (WORKLOG_REL, ARCHIVE_REL, ESCALATIONS_REL, COST_REL,
                  SELF_REVIEW_REL, QUALITY_REL, ".git/HEAD", ".git/logs/HEAD")

# Toggle for the self-check to exercise the plain-LIKE fallback path.
_FORCE_NO_FTS = False


def _now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def _subject(e: dict[str, Any]) -> str:
    """A record's subject: ``"self"`` for the harness, or a target name. Missing ==
    ``"self"`` (roadmap risk #2: retrofitting old entries isn't worth it, and target
    flows barely wrote records before this dimension existed)."""
    return str(e.get("subject") or "self")


# -- G3a: supersession (derived, append-only — a target entry is NEVER mutated) ----

def _norm_key(title: Any) -> str:
    """Normalized title key: lowercase, whitespace-collapsed. The natural key a
    supersede points at and the contradiction rule (phase 2) will collide on."""
    return " ".join(str(title or "").lower().split())


def _superseded_indices(entries: list[dict[str, Any]]) -> set[int]:
    """Indices of entries that a LATER entry supersedes.

    An entry E is superseded iff some OTHER entry S carries ``supersedes ==
    norm(E.title)`` and is newer-or-equal (``S.at >= E.at`` — you cannot supersede
    something that did not yet exist). Supersession is derived here on read, so the
    target is never mutated (anti trust-laundering: the original record is untouched
    and stays searchable). O(n²) over the ≤300-entry hot window — fine at this size.
    """
    sup: set[int] = set()
    for i, e in enumerate(entries):
        key = _norm_key(e.get("title"))
        e_at = str(e.get("at") or "")
        for j, s in enumerate(entries):
            if j == i:
                continue
            if s.get("supersedes") == key and str(s.get("at") or "") >= e_at:
                sup.add(i)
                break
    return sup


# -- canonical worklog (bounded tracked JSON, never-crash writer) -------------

def _load(root: Path, rel: str) -> list[dict[str, Any]]:
    try:
        data = read_json(root / rel, {}) or {}
    except (json.JSONDecodeError, OSError):
        return []
    if not isinstance(data, dict) or data.get("schemaVersion") != 1:
        return []
    return [e for e in data.get("entries") or [] if isinstance(e, dict)]


def _write(root: Path, rel: str, entries: list[dict[str, Any]]) -> None:
    """Write + one retry for OneDrive-style transient locks; never raises."""
    for attempt in (0, 1):
        try:
            write_json(root / rel, {"schemaVersion": 1, "entries": entries})
            return
        except OSError:
            if attempt:
                return
            time.sleep(0.2)
        except Exception:
            return


def add_entry(root: Path, kind: str, title: str, body: str = "",
              refs: Any = (), tags: Any = (), supersedes: str = "",
              subject: str = "self") -> dict[str, Any]:
    """Append a historical record to the hot worklog; spill oldest to archive.

    The ONLY sanctioned write path for new records (markdown ledgers are
    retired). Rerenders the always-in-context head afterwards.

    ``supersedes`` (G3a) names the title of an earlier record this one replaces.
    The entry it points at is demoted to the archive AHEAD of the age-based cut
    (decay = early demotion) but is never mutated or deleted — eviction ≠ deletion,
    so a superseded record stays in the archive index, ranked below live.

    ``subject`` credits the record's owner: ``"self"`` (the harness) or a target
    name, so target work stops pooling into the harness worklog + head uncredited.
    Stamped only when non-default (mirrors ``supersedes``): a ``"self"`` entry is
    byte-identical to a pre-subject entry, so every existing caller is unchanged.
    """
    if kind not in LOG_KINDS:
        raise ValueError(f"unknown kind {kind!r}; expected one of {', '.join(LOG_KINDS)}")
    entry = {"at": _now(), "kind": kind, "title": title, "body": body,
             "refs": [str(r) for r in refs], "tags": [str(t) for t in tags]}
    if supersedes:
        entry["supersedes"] = _norm_key(supersedes)
    if subject and subject != "self":
        entry["subject"] = subject
    entries = _load(root, WORKLOG_REL)
    entries.append(entry)
    to_archive: list[dict[str, Any]] = []
    # G3a: early demotion — move any entry a newer entry supersedes to the archive
    # before the age-based cut, freeing hot-window room for still-live records.
    sup = _superseded_indices(entries)
    if sup:
        to_archive = [e for i, e in enumerate(entries) if i in sup]
        entries = [e for i, e in enumerate(entries) if i not in sup]
    if len(entries) > HOT_MAX:
        to_archive = entries[:-HOT_MAX] + to_archive  # oldest-by-age first, then superseded
        entries = entries[-HOT_MAX:]
    if to_archive:
        archive = _load(root, ARCHIVE_REL)
        archive.extend(to_archive)
        _write(root, ARCHIVE_REL, archive)
    _write(root, WORKLOG_REL, entries)
    render_head(root)
    return entry


def tail(root: Path, n: int = 8) -> list[dict[str, Any]]:
    """Last n worklog entries, newest first, as compact ledger-card handles."""
    return [{"kind": e.get("kind"), "title": e.get("title"), "refs": e.get("refs") or [],
             "tags": e.get("tags") or [], "at": e.get("at")}
            for e in _load(root, WORKLOG_REL)[-n:][::-1]]


def head_commit(root: Path) -> tuple[str, str, str]:
    """(subject, body, sha) of HEAD, or ("","","") when git is unavailable."""
    try:
        proc = subprocess.run(["git", "log", "-1", "--format=%s%n%H%n%b"], cwd=root,
                              capture_output=True, text=True, encoding="utf-8",
                              errors="replace", timeout=30)
        if proc.returncode != 0:
            return ("", "", "")
        lines = proc.stdout.splitlines()
        subject = lines[0] if lines else ""
        sha = lines[1] if len(lines) > 1 else ""
        body = "\n".join(lines[2:]).strip()
        return (subject, body, sha)
    except Exception:
        return ("", "", "")


# -- derived index (SQLite/FTS5, rebuilt on demand) --------------------------

def _fts_available() -> bool:
    if _FORCE_NO_FTS:
        return False
    try:
        con = sqlite3.connect(":memory:")
        con.execute("CREATE VIRTUAL TABLE t USING fts5(x)")
        con.close()
        return True
    except Exception:
        return False


def _row(at: Any, kind: str, title: Any, body: Any, source: str, ref: Any,
         superseded: int = 0, subject: str = "self") -> dict[str, Any]:
    return {"at": str(at or ""), "kind": kind, "title": str(title or ""),
            "body": str(body or ""), "source": source, "ref": str(ref or ""),
            "superseded": int(superseded), "subject": str(subject or "self")}


def collect_records(root: Path) -> list[dict[str, Any]]:
    """Every project record as flat rows. Each reader degrades on missing/corrupt
    input (skipped, never raised) so one bad file cannot sink the index."""
    rows: list[dict[str, Any]] = []

    try:
        worklog, archive = _load(root, WORKLOG_REL), _load(root, ARCHIVE_REL)
        tagged = [(e, WORKLOG_REL) for e in worklog] + [(e, ARCHIVE_REL) for e in archive]
        sup = _superseded_indices([e for e, _ in tagged])  # G3a: rank superseded below live
        for idx, (e, rel) in enumerate(tagged):
            rows.append(_row(e.get("at"), str(e.get("kind") or "note"), e.get("title"),
                             e.get("body"), rel, " ".join(str(r) for r in e.get("refs") or []),
                             superseded=1 if idx in sup else 0, subject=_subject(e)))
    except Exception:
        pass

    try:
        esc = read_json(root / ESCALATIONS_REL, {}) or {}
        for v in (esc.get("raised") or {}).values():
            rows.append(_row(v.get("raisedAt"), "escalation", v.get("taskId") or v.get("escalationId"),
                             v.get("reason"), ESCALATIONS_REL, v.get("escalationId")))
        for v in (esc.get("resolvedRecords") or {}).values():
            rows.append(_row(v.get("resolvedAt") or v.get("raisedAt"), "escalation-resolved",
                             v.get("taskId") or v.get("escalationId"), v.get("reason"),
                             ESCALATIONS_REL, v.get("escalationId")))
    except Exception:
        pass

    try:
        for r in (read_json(root / COST_REL, {}) or {}).get("records") or []:
            if not isinstance(r, dict):
                continue
            model, wfid = r.get("model"), r.get("workflowId")
            body = {k: r.get(k) for k in ("engine", "target", "type", "status", "costUsd", "estTokens")
                    if r.get(k) is not None}
            rows.append(_row(r.get("at"), str(r.get("kind") or "cost"), model or wfid,
                             json.dumps(body, ensure_ascii=False), COST_REL, wfid or model))
    except Exception:
        pass

    try:
        sr = read_json(root / SELF_REVIEW_REL, {}) or {}
        at = sr.get("runAt")
        for f in sr.get("findings") or []:
            if isinstance(f, dict):
                rows.append(_row(at, "finding", f.get("title") or f.get("id"),
                                 f"{f.get('observed') or ''} | {f.get('proposedAction') or ''}",
                                 SELF_REVIEW_REL, f.get("id")))
    except Exception:
        pass

    try:
        qs = read_json(root / QUALITY_REL, {}) or {}
        lv = qs.get("lastValidation")
        if isinstance(lv, dict):
            rows.append(_row(lv.get("validatedAt"), "validation", f"{lv.get('gate')} {lv.get('status')}",
                             json.dumps(lv.get("counts") or {}, ensure_ascii=False), QUALITY_REL, lv.get("gate")))
        for rf in qs.get("recentFailures") or []:
            if isinstance(rf, dict):
                rows.append(_row(rf.get("validatedAt") or rf.get("at"), "validation",
                                 f"failure: {rf.get('gate')}",
                                 ", ".join(str(n) for n in rf.get("failureNames") or []),
                                 QUALITY_REL, rf.get("gate")))
    except Exception:
        pass

    try:
        for spec in sorted((root / "specs").rglob("*.md")):
            try:
                text = spec.read_text(encoding="utf-8", errors="ignore")
            except OSError:
                continue
            h1, status = "", ""
            for line in text.splitlines():
                if not h1 and line.startswith("# "):
                    h1 = line[2:].strip()
                if line.startswith("Status:"):
                    status = line.strip()
                    break
            if status:
                rel = spec.relative_to(root).as_posix()
                rows.append(_row("", "spec", h1 or spec.stem, status, rel, rel))
    except Exception:
        pass

    try:
        proc = subprocess.run(
            ["git", "log", "-n", "300", "--format=%H%x1f%aI%x1f%s%x1f%b%x1e"],
            cwd=root, capture_output=True, text=True, encoding="utf-8",
            errors="replace", timeout=60)
        if proc.returncode == 0:
            for chunk in proc.stdout.split("\x1e"):
                chunk = chunk.strip("\n")
                if not chunk:
                    continue
                parts = chunk.split("\x1f")
                if len(parts) < 4:
                    continue
                sha, at, subject, body = parts[0], parts[1], parts[2], parts[3]
                rows.append(_row(at, "commit", subject, body.strip(), "git", sha[:9]))
    except Exception:
        pass

    return rows


def build_index(root: Path) -> int:
    """Drop + recreate the derived index from collect_records(). Returns row count."""
    rows = collect_records(root)
    db = root / DB_REL
    db.parent.mkdir(parents=True, exist_ok=True)
    con = sqlite3.connect(str(db))
    try:
        con.execute("DROP TABLE IF EXISTS records_fts")
        con.execute("DROP TABLE IF EXISTS records")
        con.execute("CREATE TABLE records "
                    "(id INTEGER PRIMARY KEY, at TEXT, kind TEXT, title TEXT, body TEXT, "
                    "source TEXT, ref TEXT, superseded INTEGER DEFAULT 0, subject TEXT DEFAULT 'self')")
        con.executemany(
            "INSERT INTO records (at, kind, title, body, source, ref, superseded, subject) VALUES (?,?,?,?,?,?,?,?)",
            [(r["at"], r["kind"], r["title"], r["body"], r["source"], r["ref"],
              r.get("superseded", 0), r.get("subject", "self")) for r in rows])
        if _fts_available():
            con.execute("CREATE VIRTUAL TABLE records_fts USING fts5"
                        "(title, body, content='records', content_rowid='id')")
            con.execute("INSERT INTO records_fts(rowid, title, body) SELECT id, title, body FROM records")
        con.commit()
    finally:
        con.close()
    return len(rows)


def _index_stale(root: Path) -> bool:
    db = root / DB_REL
    if not db.exists():
        return True
    try:
        db_m = db.stat().st_mtime
    except OSError:
        return True
    for rel in _STALE_SOURCES:
        p = root / rel
        try:
            if p.exists() and p.stat().st_mtime > db_m:
                return True
        except OSError:
            pass
    try:
        for spec in (root / "specs").rglob("*.md"):
            if spec.stat().st_mtime > db_m:
                return True
    except OSError:
        pass
    return False


def _ensure_index(root: Path) -> None:
    if _index_stale(root):
        build_index(root)


def _trunc(text: str, limit: int = 200) -> str:
    text = text or ""
    return text if len(text) <= limit else text[: limit - 1] + "…"


def _compact(row: tuple) -> dict[str, Any]:
    at, kind, title, body, source, ref, subject = row
    # Handles only: full body lives at source+ref, dereferenced just-in-time.
    return {"at": at, "kind": kind, "title": _trunc(title), "body": _trunc(body),
            "source": source, "ref": ref, "subject": subject}


def _fts_query(terms: str) -> str:
    # Quote each term as a phrase (implicit AND); strips FTS operator chars.
    words = [w.replace('"', "") for w in terms.split() if w.strip()]
    return " ".join(f'"{w}"' for w in words) or '""'


def search(root: Path, terms: str, kind: str | None = None, limit: int = 10,
           subject: str | None = None) -> list[dict[str, Any]]:
    """Full-text (FTS5) or plain-LIKE search; returns compact handles. ``subject``
    (queryable) confines results to one subject's view; None = all subjects."""
    _ensure_index(root)
    con = sqlite3.connect(str(root / DB_REL))
    try:
        has_fts = bool(con.execute(
            "SELECT 1 FROM sqlite_master WHERE type='table' AND name='records_fts'").fetchone())
        if has_fts and terms.strip():
            q = ("SELECT r.at, r.kind, r.title, r.body, r.source, r.ref, r.subject "
                 "FROM records_fts f JOIN records r ON r.id = f.rowid "
                 "WHERE records_fts MATCH ?")
            params: list[Any] = [_fts_query(terms)]
            if kind:
                q += " AND r.kind = ?"
                params.append(kind)
            if subject:
                q += " AND r.subject = ?"
                params.append(subject)
            q += " ORDER BY r.superseded ASC, f.rank LIMIT ?"  # G3a: superseded stays searchable, ranks last
            params.append(limit)
        else:
            clauses, params = [], []
            for w in terms.split():
                clauses.append("(title LIKE ? OR body LIKE ?)")
                params += [f"%{w}%", f"%{w}%"]
            where = " AND ".join(clauses) or "1=1"
            q = f"SELECT at, kind, title, body, source, ref, subject FROM records WHERE {where}"
            if kind:
                q += " AND kind = ?"
                params.append(kind)
            if subject:
                q += " AND subject = ?"
                params.append(subject)
            q += " ORDER BY superseded ASC, at DESC LIMIT ?"  # G3a: superseded ranks last, still returned
            params.append(limit)
        rows = con.execute(q, params).fetchall()
    finally:
        con.close()
    return [_compact(r) for r in rows]


def summarize(root: Path, terms: str | None = None, kind: str | None = None,
              limit: int = 200) -> dict[str, Any]:
    """Deterministic digest of records returned by the existing query path."""
    rows = search(root, terms or "", kind=kind, limit=limit)
    dated = [str(row.get("at")) for row in rows if row.get("at")]
    ordered = sorted(rows, key=lambda row: str(row.get("at") or ""), reverse=True)
    kinds = sorted({str(row.get("kind")) for row in rows if row.get("kind")})
    subjects = sorted({str(row.get("subject")) for row in rows if row.get("subject")})
    return {
        "count": len(rows),
        "byKind": {value: sum(row.get("kind") == value for row in rows) for value in kinds},
        "dateRange": {"oldest": min(dated) if dated else None,
                      "newest": max(dated) if dated else None},
        "bySubject": {value: sum(row.get("subject") == value for row in rows)
                      for value in subjects},
        "topSources": [{"title": row.get("title") or row.get("ref"),
                        "at": row.get("at"), "kind": row.get("kind")}
                       for row in ordered[:10]],
        "terms": terms,
        "kind": kind,
        "limit": limit,
    }


def recent(root: Path, kind: str | None = None, limit: int = 20,
           subject: str | None = None) -> list[dict[str, Any]]:
    """Most-recent records (by `at`, descending); compact handles. ``subject``
    (queryable) confines results to one subject's view; None = all subjects."""
    _ensure_index(root)
    con = sqlite3.connect(str(root / DB_REL))
    try:
        q = "SELECT at, kind, title, body, source, ref, subject FROM records"
        clauses, params = [], []
        if kind:
            clauses.append("kind = ?")
            params.append(kind)
        if subject:
            clauses.append("subject = ?")
            params.append(subject)
        if clauses:
            q += " WHERE " + " AND ".join(clauses)
        q += " ORDER BY superseded ASC, at DESC LIMIT ?"  # G3a: live before superseded
        params.append(limit)
        rows = con.execute(q, params).fetchall()
    finally:
        con.close()
    return [_compact(r) for r in rows]


# -- always-in-context head (marker-delimited, byte-stable) ------------------

def render_head(root: Path) -> None:
    """Rewrite the ledger:head section of LEDGER_HEAD.md (class B, untracked).
    Never touches text outside the markers; byte-identical output when the
    inputs are unchanged."""
    entries = _load(root, WORKLOG_REL)
    # Subject-scoped head: only the harness's own ("self") rows reach the
    # always-in-context head, so a target's work doesn't silently pool into every
    # session's head. Missing subject == "self", so pre-subject worklogs render
    # byte-for-byte as before (per-subject heads deferred — YAGNI until a real
    # per-target chat session exists).
    entries = [e for e in entries if _subject(e) == "self"]
    # G3a: a superseded record must not sit in the always-in-context head (add_entry
    # already demotes it, but filter defensively when render_head is called alone).
    sup = _superseded_indices(entries)
    entries = [e for i, e in enumerate(entries) if i not in sup]
    content = ["## Ledger head", ""]
    for e in entries[-8:][::-1]:
        ref = " ".join(str(r) for r in e.get("refs") or [])
        title = str(e.get("title") or "").strip()
        content.append(f"- [{e.get('kind')}] {title}" + (f" ({ref})" if ref else ""))
    esc = read_json(root / ESCALATIONS_REL, {}) or {}
    resolved = set(esc.get("resolvedIds") or [])
    pending = sum(1 for eid, v in (esc.get("raised") or {}).items()
                  if eid not in resolved and str((v or {}).get("criticality")) in ("high", "critical"))
    content += ["", f"Pending high/critical escalations: {pending}",
                "More: python scripts/harness.py records search <terms>"]
    # Cap total lines (markers inclusive) at HEAD_MAX_LINES.
    content = content[: HEAD_MAX_LINES - 2]
    section = "\n".join([HEAD_START, *content, HEAD_END])

    path = root / LEDGER_HEAD_REL
    try:
        text = path.read_text(encoding="utf-8")
    except OSError:
        text = ""
    if HEAD_START in text and HEAD_END in text:
        head, rest = text.split(HEAD_START, 1)
        _, tail = rest.split(HEAD_END, 1)
        new_text = head.rstrip("\n") + "\n\n" + section + "\n" + tail.lstrip("\n")
    elif text.strip():
        new_text = text.rstrip("\n") + "\n\n" + section + "\n"
    else:
        new_text = section + "\n"
    if new_text != text:
        write_text(path, new_text)


# -- deterministic self-check ------------------------------------------------

def _self_check() -> None:
    global _FORCE_NO_FTS
    import tempfile
    tmp = Path(tempfile.mkdtemp())

    # add_entry validation
    try:
        add_entry(tmp, "not-a-kind", "x")
        raise AssertionError("bad kind should have raised")
    except ValueError:
        pass

    # bounded hot 300 + archive spill
    for i in range(305):
        add_entry(tmp, "note", f"entry {i}", body="zebracorn" if i == 0 else "", tags=["seed"])
    hot = _load(tmp, WORKLOG_REL)
    archive = _load(tmp, ARCHIVE_REL)
    assert len(hot) == HOT_MAX, len(hot)
    assert len(archive) == 5, len(archive)
    assert archive[0]["title"] == "entry 0"  # oldest spilled first (carries the seed term)

    # synthetic escalations + cost shapes flow into collect_records
    (tmp / ESCALATIONS_REL).parent.mkdir(parents=True, exist_ok=True)
    write_json(tmp / ESCALATIONS_REL, {
        "raised": {"self-review/x": {"escalationId": "self-review/x", "taskId": "x",
                                     "reason": "seeded", "raisedAt": "2026-07-10T00:00:00+00:00",
                                     "criticality": "high"}},
        "resolvedIds": [],
        "resolvedRecords": {"old": {"escalationId": "old", "reason": "done",
                                    "resolvedAt": "2026-07-09T00:00:00+00:00"}}})
    write_json(tmp / COST_REL, {"schemaVersion": 1, "records": [
        {"at": "2026-07-10T00:00:00+00:00", "kind": "workflow", "workflowId": "WF-1",
         "type": "map-reduce", "estTokens": 1000}]})
    rows = collect_records(tmp)
    kinds = {r["kind"] for r in rows}
    assert {"note", "escalation", "escalation-resolved", "workflow"} <= kinds, kinds
    assert any(r["ref"] == "self-review/x" for r in rows)

    # FTS search finds the seeded term (in the archive)
    _FORCE_NO_FTS = False
    if _fts_available():
        build_index(tmp)
        hits = search(tmp, "zebracorn")
        assert hits and any("entry 0" in h["title"] for h in hits), hits

    # forced plain-LIKE fallback finds the same term
    _FORCE_NO_FTS = True
    build_index(tmp)
    con = sqlite3.connect(str(tmp / DB_REL))
    assert not con.execute("SELECT 1 FROM sqlite_master WHERE name='records_fts'").fetchone()
    con.close()
    hits = search(tmp, "zebracorn")
    assert hits and any("entry 0" in h["title"] for h in hits), hits
    _FORCE_NO_FTS = False

    # kind filter on recent
    build_index(tmp)
    only_wf = recent(tmp, kind="workflow")
    assert only_wf and all(r["kind"] == "workflow" for r in only_wf), only_wf

    # staleness rebuild after a source is touched
    build_index(tmp)
    assert not _index_stale(tmp)
    time.sleep(0.02)
    add_entry(tmp, "note", "fresh milestone", body="uniquetokenXYZ")
    assert _index_stale(tmp)
    assert search(tmp, "uniquetokenXYZ"), "search must rebuild a stale index"

    # handles never carry huge bodies
    add_entry(tmp, "note", "big", body="A" * 5000)
    build_index(tmp)
    for hit in recent(tmp, limit=50):
        assert len(hit["body"]) <= 201, len(hit["body"])

    # render_head: idempotent bytes, <=30 lines, preserves outside-marker text
    ctx = tmp / LEDGER_HEAD_REL
    ctx.parent.mkdir(parents=True, exist_ok=True)
    write_text(ctx, "# Context\n\nkeep me\n")
    render_head(tmp)
    first = ctx.read_text(encoding="utf-8")
    render_head(tmp)
    second = ctx.read_text(encoding="utf-8")
    assert first == second, "render_head must be byte-stable"
    assert "keep me" in second, "outside-marker text must be preserved"
    block = second.split(HEAD_START, 1)[1].split(HEAD_END, 1)[0]
    total_lines = len([HEAD_START]) + block.count("\n") + len([HEAD_END])
    assert total_lines <= HEAD_MAX_LINES, total_lines

    # G3a: supersession — target demotes EARLY to archive, drops from head, stays
    # searchable but ranks below the live record; the target is never mutated.
    sup_tmp = Path(tempfile.mkdtemp())
    add_entry(sup_tmp, "decision", "Adopt approach ALPHA", body="sharedterm ALPHA path")
    time.sleep(0.02)
    add_entry(sup_tmp, "decision", "Adopt approach BETA", body="sharedterm BETA path",
              supersedes="Adopt approach ALPHA")
    hot_titles = [e["title"] for e in _load(sup_tmp, WORKLOG_REL)]
    arch = _load(sup_tmp, ARCHIVE_REL)
    assert "Adopt approach ALPHA" in [e["title"] for e in arch] and "Adopt approach ALPHA" not in hot_titles, (hot_titles, arch)
    assert "Adopt approach BETA" in hot_titles, hot_titles
    assert all("supersedes" not in e for e in arch), "target must not be mutated (append-only supersession)"
    ctx2 = sup_tmp / LEDGER_HEAD_REL
    ctx2.parent.mkdir(parents=True, exist_ok=True)
    write_text(ctx2, "# Context\n\n")
    render_head(sup_tmp)
    head_txt = ctx2.read_text(encoding="utf-8")
    assert "BETA" in head_txt and "ALPHA" not in head_txt, "superseded record must drop from the head"
    if _fts_available():
        build_index(sup_tmp)
        titles = [h["title"] for h in search(sup_tmp, "sharedterm")]
        assert "Adopt approach ALPHA" in titles, "superseded record must STAY searchable"
        assert titles.index("Adopt approach BETA") < titles.index("Adopt approach ALPHA"), f"live must rank above superseded: {titles}"

    # subject dimension: a target entry is stamped, stored + searchable, and stays
    # OUT of the default (self) head, while a self entry stays IN.
    subj_tmp = Path(tempfile.mkdtemp())
    self_e = add_entry(subj_tmp, "milestone", "harness ships records subject", body="selfterm")
    tgt_e = add_entry(subj_tmp, "milestone", "target ACME gate green", body="targetterm",
                      subject="acme")
    assert "subject" not in self_e, "default self must NOT stamp subject (byte-identical)"
    assert tgt_e.get("subject") == "acme", tgt_e
    assert _subject(self_e) == "self" and _subject(tgt_e) == "acme"
    build_index(subj_tmp)
    # searchable + queryable by subject
    assert search(subj_tmp, "targetterm", subject="acme"), "target entry must be searchable"
    assert not search(subj_tmp, "targetterm", subject="self"), "subject filter must confine"
    assert {h["subject"] for h in recent(subj_tmp, subject="acme")} == {"acme"}, "recent must filter subject"
    # default (self) head shows the self entry, hides the target entry
    ctx3 = subj_tmp / LEDGER_HEAD_REL
    ctx3.parent.mkdir(parents=True, exist_ok=True)
    write_text(ctx3, "# Context\n\n")
    render_head(subj_tmp)
    head3 = ctx3.read_text(encoding="utf-8")
    assert "harness ships records subject" in head3, "self entry must render in the self head"
    assert "target ACME gate green" not in head3, "target entry must NOT pool into the self head"

    print("records self-check ok")


